use std::mem;

#[allow(unused)]
#[repr(u8)]
#[derive(Debug)]
pub enum OpCode {
    Pop = 0x00,
    ReturnVoid = 0x01,
    ReturnValue = 0x02,
    Constant = 0x03,
    LongConstant = 0x04,
    StackCopy = 0x05,
    StackWrite = 0x06,
    PointerCopy = 0x07,
    PointerWrite = 0x08,
    U8Add = 0x09,
    U8Subtract = 0x0A,
    U8Multiply = 0x0B,
    U8Divide = 0x0C,
    U16Add = 0x0D,
    U16Subtract = 0x0E,
    U16Multiply = 0x0F,
    U16Divide = 0x10,
    U32Add = 0x11,
    U32Subtract = 0x12,
    U32Multiply = 0x13,
    U32Divide = 0x14,
    U64Add = 0x15,
    U64Subtract = 0x16,
    U64Multiply = 0x17,
    U64Divide = 0x18,
    I8Add = 0x19,
    I8Subtract = 0x1A,
    I8Multiply = 0x1B,
    I8Divide = 0x1C,
    I16Add = 0x1D,
    I16Subtract = 0x1E,
    I16Multiply = 0x1F,
    I16Divide = 0x20,
    I32Add = 0x21,
    I32Subtract = 0x22,
    I32Multiply = 0x23,
    I32Divide = 0x24,
    I64Add = 0x25,
    I64Subtract = 0x26,
    I64Multiply = 0x27,
    I64Divide = 0x28,
    F32Add = 0x29,
    F32Subtract = 0x2A,
    F32Multiply = 0x2B,
    F32Divide = 0x2C,
    F64Add = 0x2D,
    F64Subtract = 0x2E,
    F64Multiply = 0x2F,
    F64Divide = 0x30,
    Call = 0x31,
    DynCall = 0x32,
    SysCall = 0x33,
    PushZeroed = 0x34,
    Property = 0x35,
    Jump = 0x36,
    JumpIfZero = 0x37,
    JumpUnlessZero = 0x38,
    Equal = 0x39,
    NotEqual = 0x3a,
    U8LessThan = 0x3b,
    U8GreaterThan = 0x3c,
    U16LessThan = 0x3d,
    U16GreaterThan = 0x3e,
    U32LessThan = 0x3f,
    U32GreaterThan = 0x40,
    U64LessThan = 0x41,
    U64GreaterThan = 0x42,
    I8LessThan = 0x43,
    I8GreaterThan = 0x44,
    I16LessThan = 0x45,
    I16GreaterThan = 0x46,
    I32LessThan = 0x47,
    I32GreaterThan = 0x48,
    I64LessThan = 0x49,
    I64GreaterThan = 0x4a,
    F32LessThan = 0x4b,
    F32GreaterThan = 0x4c,
    F64LessThan = 0x4d,
    F64GreaterThan = 0x4e,
    Negate = 0x4f,

    Invalid = 0xFF,
}

impl From<u8> for OpCode {
    fn from(value: u8) -> Self {
        if value > 0x35 {
            Self::Invalid
        } else {
            // SAFETY: values bigger than the maximum are handled above
            unsafe { mem::transmute(value) }
        }
    }
}
